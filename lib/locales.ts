import { siteConfig } from '@/lib/site';

export const locales = ['es', 'de', 'vi'] as const;
export type Locale = typeof locales[number];
export const localeNames = { en: 'English', es: 'Español', de: 'Deutsch', vi: 'Tiếng Việt' };
export function isLocale(value: string): value is Locale { return locales.some(locale => locale === value); }
export const translatedSlugs = ['firelands-volatile-farm', 'burning-steppes-mageweave-runecloth-farm'] as const;
export function hasTranslation(slug: string) { return translatedSlugs.some(value => value === slug); }
export function languageAlternates(slug?: string) {
  if (slug && !hasTranslation(slug)) return undefined;
  const english = `${siteConfig.domain}/guides${slug ? `/${slug}` : ''}`;
  return Object.fromEntries([
    ['en', english],
    ...locales.map(locale => [locale, `${siteConfig.domain}/${locale}${slug ? `/guides/${slug}` : ''}`]),
    ['x-default', english],
  ]);
}
